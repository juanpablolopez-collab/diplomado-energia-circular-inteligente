    class HogarAdopcionNet(nn.Module):
        def __init__(self, n_num, cat_card, n_horas=24, n_classes=3, emb_max=16, dropout=0.3):
            super().__init__()
            self.mlp_num = nn.Sequential(
                nn.Linear(n_num, 128), nn.BatchNorm1d(128), nn.GELU(), nn.Dropout(0.2),
                nn.Linear(128, 64), nn.GELU(), nn.LayerNorm(64)
            )
            self.emb_dims = {c: min(emb_max, max(2, (card + 1) // 2)) for c, card in cat_card.items()}
            self.embs = nn.ModuleDict({c: nn.Embedding(card + 1, self.emb_dims[c], padding_idx=0) for c, card in cat_card.items()})
            total_emb = sum(self.emb_dims.values())
            self.cat_mlp = nn.Sequential(nn.Linear(total_emb, 64), nn.GELU(), nn.Dropout(0.2))
            self.conv = nn.Sequential(
                nn.Conv1d(1, 16, kernel_size=3, padding=1), nn.BatchNorm1d(16), nn.GELU(),
                nn.Conv1d(16, 32, kernel_size=3, padding=1), nn.BatchNorm1d(32), nn.GELU(),
                nn.AdaptiveAvgPool1d(1), nn.Flatten()
            )
            self.head_hora = nn.Sequential(nn.Linear(32, 32), nn.GELU())
            self.head = nn.Sequential(
                nn.Linear(64 + 64 + 32, 128), nn.GELU(), nn.Dropout(dropout),
                nn.Linear(128, n_classes)
            )
            self.cat_cols_ordered = list(cat_card.keys())

        def forward(self, x_num, x_cat, x_hora):
            a = self.mlp_num(x_num)
            embs = [self.embs[c](x_cat[:, i]) for i, c in enumerate(self.cat_cols_ordered)]
            b = self.cat_mlp(torch.cat(embs, dim=1))
            c = self.head_hora(self.conv(x_hora.unsqueeze(1)))
            return self.head(torch.cat([a, b, c], dim=1))

    class TorchTabularClassifier(BaseEstimator, ClassifierMixin):
        _estimator_type = "classifier"

        def __sklearn_tags__(self):
            tags = super().__sklearn_tags__()
            tags.estimator_type = "classifier"
            return tags

        def __init__(self, num_cols, cat_cols, hora_cols, epochs=40, batch_size=64, lr=3e-4,
                     weight_decay=1e-4, patience=8, dropout=0.3, seed=SEED, device=None):
            self.num_cols = num_cols
            self.cat_cols = cat_cols
            self.hora_cols = hora_cols
            self.epochs = epochs
            self.batch_size = batch_size
            self.lr = lr
            self.weight_decay = weight_decay
            self.patience = patience
            self.dropout = dropout
            self.seed = seed
            self.device = str(device) if device is not None else None

        def _prep_fit(self, X):
            self.scaler_num_ = StandardScaler().fit(X[self.num_cols].values)
            self.enc_cat_ = {}
            self.cat_card_ = {}
            for c in self.cat_cols:
                le = LabelEncoder().fit(X[c].astype(str).values)
                self.enc_cat_[c] = le
                self.cat_card_[c] = len(le.classes_)
            H = X[self.hora_cols].values.astype(float)
            self.scaler_hora_ = StandardScaler().fit(H / np.clip(H.sum(1, keepdims=True), 1e-9, None))
            return self

        def _transform(self, X):
            xn = self.scaler_num_.transform(X[self.num_cols].values).astype(np.float32)
            xc = np.zeros((len(X), len(self.cat_cols)), dtype=np.int64)
            for i, c in enumerate(self.cat_cols):
                le = self.enc_cat_[c]
                mapeado = {cl: j + 1 for j, cl in enumerate(le.classes_)}
                xc[:, i] = [mapeado.get(v, 0) for v in X[c].astype(str).values]
            H = X[self.hora_cols].values.astype(float)
            Hn = H / np.clip(H.sum(1, keepdims=True), 1e-9, None)
            xh = self.scaler_hora_.transform(Hn).astype(np.float32)
            return xn, xc, xh

        def fit(self, X, y):
            X = X.reset_index(drop=True)
            y = np.asarray(y).astype(int)
            self._prep_fit(X)
            xn, xc, xh = self._transform(X)
            n_tr = int(0.85 * len(X))
            idx = np.arange(len(X))
            rng = np.random.default_rng(self.seed)
            rng.shuffle(idx)
            tr, va = idx[:n_tr], idx[n_tr:]
            dev = torch.device(self.device) if self.device else (
                torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")
            )
            self.device_ = str(dev)
            self.model_ = HogarAdopcionNet(
                n_num=xn.shape[1],
                cat_card={c: self.cat_card_[c] for c in self.cat_cols},
                n_horas=xh.shape[1], n_classes=3, dropout=self.dropout
            ).to(dev)
            self.model_.cat_cols_ordered = self.cat_cols
            cnt = np.bincount(y, minlength=3).astype(float)
            w = (len(y) / (3 * np.clip(cnt, 1, None)))
            crit = nn.CrossEntropyLoss(weight=torch.tensor(w, dtype=torch.float32, device=dev))
            opt = torch.optim.AdamW(self.model_.parameters(), lr=self.lr, weight_decay=self.weight_decay)
            sched = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(opt, T_0=10, T_mult=2)
            Xn_t = torch.tensor(xn, device=dev)
            Xc_t = torch.tensor(xc, device=dev)
            Xh_t = torch.tensor(xh, device=dev)
            y_t = torch.tensor(y, device=dev)
            best_f1, best_state, bad = -1.0, None, 0
            self.history_ = {"epoch": [], "loss_tr": [], "loss_va": [], "f1_va": []}
            for ep in range(self.epochs):
                self.model_.train()
                perm = torch.randperm(n_tr, device=dev)
                tot_loss = 0.0
                for i in range(0, n_tr, self.batch_size):
                    b = perm[i:i + self.batch_size]
                    gidx = torch.tensor(tr, device=dev)[b]
                    logits = self.model_(Xn_t[gidx], Xc_t[gidx], Xh_t[gidx])
                    loss = crit(logits, y_t[gidx])
                    opt.zero_grad(); loss.backward(); opt.step()
                    tot_loss += loss.item() * len(b)
                sched.step()
                self.model_.eval()
                with torch.no_grad():
                    gv = torch.tensor(va, device=dev)
                    logits = self.model_(Xn_t[gv], Xc_t[gv], Xh_t[gv])
                    loss_v = crit(logits, y_t[gv]).item()
                    pv = torch.softmax(logits, 1).cpu().numpy().argmax(1)
                f1v = f1_score(y[va], pv, average="macro")
                self.history_["epoch"].append(ep + 1)
                self.history_["loss_tr"].append(tot_loss / n_tr)
                self.history_["loss_va"].append(loss_v)
                self.history_["f1_va"].append(f1v)
                if f1v > best_f1 + 1e-4:
                    best_f1 = f1v
                    bad = 0
                    best_state = {k: v.detach().cpu().clone() for k, v in self.model_.state_dict().items()}
                else:
                    bad += 1
                    if bad >= self.patience:
                        break
            if best_state is not None:
                self.model_.load_state_dict(best_state)
            self.best_f1_ = best_f1
            self.classes_ = np.array([0, 1, 2])
            return self

        def predict_proba(self, X):
            from sklearn.utils.validation import check_is_fitted
            check_is_fitted(self, ["model_"])
            X = X.reset_index(drop=True)
            xn, xc, xh = self._transform(X)
            dev = torch.device(self.device_) if self.device_ else (
                torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")
            )
            self.model_.eval()
            with torch.no_grad():
                logits = self.model_(
                    torch.tensor(xn, device=dev),
                    torch.tensor(xc, device=dev),
                    torch.tensor(xh, device=dev),
                )
                return torch.softmax(logits, 1).cpu().numpy()

        def predict(self, X):
            return self.predict_proba(X).argmax(1)


