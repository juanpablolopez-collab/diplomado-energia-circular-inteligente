def _resolver_pulp(beneficio, costo, caps, presupuesto, min_share):
    prob = pulp.LpProblem("Subsidios_FV_Popayan", pulp.LpMaximize)
    x = {s: pulp.LpVariable(f"E{s}", 0, caps[s], pulp.LpInteger) for s in (1, 2, 3)}
    prob += pulp.lpSum(beneficio[s] * x[s] for s in x), "Beneficio_total"
    prob += pulp.lpSum(costo[s] * x[s] for s in x) <= presupuesto, "Presupuesto"
    if min_share > 0:
        prob += costo[1] * x[1] - min_share * pulp.lpSum(costo[s] * x[s] for s in x) >= 0, "Equidad_E1"
    prob.solve(pulp.PULP_CBC_CMD(msg=0))
    if pulp.LpStatus[prob.status] != "Optimal":
        return None, pulp.LpStatus[prob.status]
    return {s: int(round(x[s].value() or 0)) for s in x}, "Optimal"
def _resolver_scipy(beneficio, costo, caps, presupuesto, min_share):
    from scipy.optimize import milp, LinearConstraint, Bounds
    c = -np.array([beneficio[s] for s in (1, 2, 3)])
    co = np.array([costo[s] for s in (1, 2, 3)])
    A = [co]; ub = [presupuesto]
    if min_share > 0:
        fila = min_share * co.copy(); fila[0] = -(1 - min_share) * co[0]
        A.append(fila); ub.append(0.0)
    r = milp(c, constraints=LinearConstraint(np.array(A), -np.inf, np.array(ub)), integrality=np.ones(3),
             bounds=Bounds(np.zeros(3), np.array([caps[s] for s in (1, 2, 3)], float)))
    if not r.success:
        return None, r.message
    return {s: int(round(r.x[i])) for i, s in enumerate((1, 2, 3))}, "Optimal"
