def brier_multiclase(y, P):
    Y = np.eye(P.shape[1])[y]
    return float(np.mean(np.sum((P - Y) ** 2, axis=1)))

def ece_multiclase(y, P, bins=10):
    conf = P.max(axis=1); pred = P.argmax(axis=1); ok = (pred == y).astype(float)
    edges = np.linspace(0, 1, bins + 1); e = 0.0
    for i in range(bins):
        m = (conf > edges[i]) & (conf <= edges[i + 1])
        if m.any():
            e += m.mean() * abs(ok[m].mean() - conf[m].mean())
    return float(e)

def metricas_clf(y, P):
    pred = P.argmax(axis=1); Y = np.eye(P.shape[1])[y]
    return {"accuracy": accuracy_score(y, pred), "balanced_acc": balanced_accuracy_score(y, pred), "f1_macro": f1_score(y, pred, average="macro"),
            "f1_weighted": f1_score(y, pred, average="weighted"), "roc_auc_ovr": roc_auc_score(y, P, multi_class="ovr", average="macro"),
            "pr_auc_macro": float(np.mean([average_precision_score(Y[:, k], P[:, k]) for k in range(P.shape[1])])),
            "mcc": matthews_corrcoef(y, pred), "kappa": cohen_kappa_score(y, pred), "brier": brier_multiclase(y, P),
            "log_loss": log_loss(y, P, labels=[0, 1, 2]), "ece": ece_multiclase(y, P)}

