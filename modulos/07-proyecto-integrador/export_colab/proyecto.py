KG_POR_W = 0.052
MASA_INVERSOR_KG = 8.0
MODOS_RAEE = ["Weibull regular (α=5.38, β=30 años)", "Pérdida temprana (α=2.5, β=18 años)", "Retiro programado a la vida útil"]
def _F(t, a, b): return 1 - np.exp(-(np.maximum(t, 0) / b) ** a)
def simular_raee(total_sistemas=5000, potencia_w=450, paneles_por_sistema=3, modo=MODOS_RAEE[0], vida=25, factor_recuperacion=1.0, anio_ini=2026, anio_fin=2030, horizonte=2065):
    años = np.arange(anio_ini, horizonte + 1); cohortes = np.arange(anio_ini, anio_fin + 1)
    w = 1 / (1 + np.exp(-(np.linspace(-2, 2, len(cohortes))))); inst = total_sistemas * w / w.sum()
    masa_panel = potencia_w * KG_POR_W
    fin_pan = np.zeros(len(años)); fin_inv = np.zeros(len(años))
    for c, n_sis in zip(cohortes, inst):
        n_pan = n_sis * paneles_por_sistema
        for j, y in enumerate(años):
            edad = y - c
            if edad < 0: continue
            if modo.startswith("Retiro"):
                f = 1.0 if edad == vida else 0.0
            else:
                a, b = (5.38, 30.0) if modo.startswith("Weibull") else (2.5, 18.0)
                f = _F(edad + 1, a, b) - _F(edad, a, b)
            f_inv = _F(edad + 1, 3.0, 13.0) - _F(edad, 3.0, 13.0)
            fin_pan[j] += n_pan * f; fin_inv[j] += n_sis * f_inv
    res = pd.DataFrame({"año": años, "paneles_fin_vida": fin_pan, "inversores_fin_vida": fin_inv})
    res["residuo_paneles_t"] = res.paneles_fin_vida * masa_panel / 1000.0
    res["residuo_inversores_t"] = res.inversores_fin_vida * MASA_INVERSOR_KG / 1000.0
    res["residuo_total_t"] = res.residuo_paneles_t + res.residuo_inversores_t
    for mat, frac in COMPOSICION.items():
        res[f"{mat}_recuperable_t"] = res.residuo_paneles_t * frac * min(1.0, RECUPERACION[mat] * factor_recuperacion)
    res["recuperable_total_t"] = res[[c for c in res.columns if c.endswith("_recuperable_t")]].sum(axis=1)
    res["a_disposicion_final_t"] = res.residuo_paneles_t - res["recuperable_total_t"] + res.residuo_inversores_t
    return res
