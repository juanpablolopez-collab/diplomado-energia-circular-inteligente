class TorchRegressor(BaseEstimator):
    _estimator_type = "regressor"

    def __init__(self, hidden=(128, 64, 32), epochs=200, batch_size=64, lr=1e-3, patience=20, seed=SEED):
        self.hidden = hidden; self.epochs = epochs; self.batch_size = batch_size
        self.lr = lr; self.patience = patience; self.seed = seed

    def fit(self, X, y):
        X = np.asarray(X, dtype=np.float32); y = np.asarray(y, dtype=np.float32).reshape(-1, 1)
        torch.manual_seed(self.seed)
        layers = []; prev = X.shape[1]
        for h in self.hidden:
            layers += [nn.Linear(prev, h), nn.GELU(), nn.Dropout(0.15)]; prev = h
        layers += [nn.Linear(prev, 1)]
        self.net_ = nn.Sequential(*layers)
        dev = torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")
        self.net_.to(dev)
        opt = torch.optim.AdamW(self.net_.parameters(), lr=self.lr, weight_decay=1e-4)
        crit = nn.MSELoss()
        Xt = torch.tensor(X, device=dev); yt = torch.tensor(y, device=dev)
        idx = np.arange(len(X)); rng = np.random.default_rng(self.seed); rng.shuffle(idx)
        n_tr = int(0.85 * len(X)); tr, va = idx[:n_tr], idx[n_tr:]
        best_loss, bad, best_state = np.inf, 0, None
        for ep in range(self.epochs):
            self.net_.train()
            perm = torch.tensor(rng.permutation(n_tr), device=dev)
            for i in range(0, n_tr, self.batch_size):
                b = perm[i:i + self.batch_size]
                gidx = torch.tensor(tr, device=dev)[b]
                loss = crit(self.net_(Xt[gidx]), yt[gidx])
                opt.zero_grad(); loss.backward(); opt.step()
            self.net_.eval()
            with torch.no_grad():
                gv = torch.tensor(va, device=dev)
                loss_v = crit(self.net_(Xt[gv]), yt[gv]).item()
            if loss_v < best_loss - 1e-4:
                best_loss = loss_v; bad = 0
                best_state = {k: v.detach().cpu().clone() for k, v in self.net_.state_dict().items()}
            else:
                bad += 1
                if bad >= self.patience: break
        if best_state is not None: self.net_.load_state_dict(best_state)
        return self

    def predict(self, X):
        dev = next(self.net_.parameters()).device
        self.net_.eval()
        with torch.no_grad():
            Xt = torch.tensor(np.asarray(X, dtype=np.float32), device=dev)
            return self.net_(Xt).cpu().numpy().ravel()

