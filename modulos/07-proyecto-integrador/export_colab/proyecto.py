def fourier(index, K=3):
    doy = index.dayofyear.values; cols = {}
    for k in range(1, K + 1):
        cols[f"s{k}"] = np.sin(2 * np.pi * k * doy / 365.25); cols[f"c{k}"] = np.cos(2 * np.pi * k * doy / 365.25)
    return pd.DataFrame(cols, index=index)
def ajustar_sarimax(y):
    Xf = fourier(y.index)
    for orden, sord in (((1, 0, 1), (1, 0, 1, 7)), ((1, 0, 0), (1, 0, 0, 7)), ((1, 0, 0), (0, 0, 0, 0))):
        try:
            m = SARIMAX(y, exog=Xf, order=orden, seasonal_order=sord, trend="c", enforce_stationarity=False, enforce_invertibility=False)
            return m.fit(disp=False, maxiter=200), orden, sord
        except Exception:
            continue
    raise RuntimeError("SARIMAX no convergió")
def pronostico_sarimax(res, y_index_fin, h, n_sim=300):
    fidx = pd.date_range(y_index_fin + pd.Timedelta(days=1), periods=h, freq="D"); Xf = fourier(fidx)
    mean = res.get_forecast(steps=h, exog=Xf).predicted_mean.values
    try:
        sim = np.asarray(res.simulate(nsimulations=h, repetitions=n_sim, anchor="end", exog=Xf)).reshape(h, -1)
    except Exception:
        sd = float(np.std(res.resid[10:])); sim = mean[:, None] + np.random.default_rng(SEED).normal(0, sd, (h, n_sim))
    return fidx, mean, sim
