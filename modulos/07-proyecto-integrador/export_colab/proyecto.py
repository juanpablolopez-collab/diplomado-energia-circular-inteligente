def predecir_ahorro(estrato, zona, personas, consumo, tarifa, area_cub, inclin, orient, tcub, sombra, n_pan, p_pan, ratio_dia):
    kwp = n_pan * p_pan / 1000.0; area_req = n_pan * p_pan / 205.0
    aviso = "" if area_req <= 0.75 * area_cub else f"\n\n⚠️ Área requerida {area_req:.1f} m² > 75% de cubierta."
    fila = pd.DataFrame([{"estrato": int(estrato), "num_personas": personas, "consumo_kwh_mes": consumo, "tarifa_kwh_cop": tarifa, "area_cubierta_m2": area_cub,
                          "inclinacion_cubierta_grados": inclin, "num_paneles_estimados": n_pan, "potencia_panel_w": p_pan, "ratio_diurno_6_17": ratio_dia / 100.0,
                          "zona": zona, "tipo_cubierta": tcub, "orientacion_cubierta": orient, "sombras_presentes": sombra}])[FEATS_REG]
    ahorro = float(REG["ahorro_anual_cop"]["modelo"].predict(fila)[0]); ret = float(REG["retorno_simple_anios"]["modelo"].predict(fila)[0])
    factura_anual = consumo * tarifa * 12; ahorro = float(np.clip(ahorro, 0, 0.8 * factura_anual)); inv = kwp * COSTO_KWP_REF
    fig = go.Figure(go.Bar(x=["Factura anual", "Ahorro", "Con FV"], y=[factura_anual, ahorro, factura_anual - ahorro],
                           marker_color=["#7f8c8d", "#1e8449", "#2471a3"], text=[f"${v/1e6:.2f}M" for v in (factura_anual, ahorro, factura_anual - ahorro)], textposition="auto"))
    fig.update_layout(title="Impacto económico anual (COP)", height=380)
    md = (f"### Resultados\n- {kwp:.2f} kWp ({n_pan}×{p_pan} W) | área {area_req:.1f} m²\n- Ahorro anual: **${ahorro:,.0f}** ({100*ahorro/factura_anual:.0f}%)\n"
          f"- Retorno: **{ret:.1f} años** | inversión ~ **${inv:,.0f}**{aviso}")
    return md, fig

