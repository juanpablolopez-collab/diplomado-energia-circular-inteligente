def ingenieria_caracteristicas(d):
    """Variables derivadas calculables también desde el formulario del simulador."""
    d = d.copy()
    d["kwp_calc"] = d["num_paneles_estimados"] * d["potencia_panel_w"] / 1000.0
    d["carga_familiar"] = (d["num_menores"] + d["num_adultos_mayores"]) / d["num_personas"]
    d["ratio_consumo_ingreso_pct"] = 100.0 * d["consumo_kwh_mes"] * d["tarifa_kwh_cop"] / d["ingreso_mensual_cop"]
    d["kwh_por_persona"] = d["consumo_kwh_mes"] / d["num_personas"]
    d["kwh_por_m2"] = d["consumo_kwh_mes"] / d["area_vivienda_m2"]
    rpp = d["estrato"].map(REF_PP); rm2 = d["estrato"].map(REF_M2)
    d["indice_eficiencia_vivienda"] = (100.0 * (1 - 0.5 * (d["kwh_por_persona"] / (2 * rpp) + d["kwh_por_m2"] / (2 * rm2)))).clip(0, 100)
    d["cobertura_solar_pct"] = 100.0 * d["kwp_calc"] * HSP_REF * 30 * PR_REF / d["consumo_kwh_mes"]
    d["brecha_digital"] = (d["tiene_internet"] == "No").astype(int) + (d["tiene_smartphone"] == "No").astype(int)
    return d

def agregar_perfil(d):
    """Variables del perfil horario (solo disponibles en el dataset, no en los formularios)."""
    d = d.copy()
    tot = d[HORAS].sum(axis=1)
    d["ratio_diurno_6_17"] = d[[f"h{h:02d}" for h in range(6, 18)]].sum(axis=1) / tot
    d["ratio_manana_6_8"] = d[["h06", "h07", "h08"]].sum(axis=1) / tot
    d["ratio_mediodia_12_14"] = d[["h12", "h13", "h14"]].sum(axis=1) / tot
    d["ratio_noche_18_22"] = d[[f"h{h:02d}" for h in range(18, 23)]].sum(axis=1) / tot
    d["ratio_madrugada_0_5"] = d[[f"h{h:02d}" for h in range(0, 6)]].sum(axis=1) / tot
    d["factor_pico_horario"] = d[HORAS].max(axis=1) / d[HORAS].mean(axis=1)
    return d

