def reg_fig(nombre, fig, clave=False):
    """Registra una figura Plotly, la exporta a HTML (siempre) y a PNG (solo claves, si kaleido funciona)."""
    FIGS[nombre] = fig
    try:
        fig.write_html(f"{DIRS['graficos']}/{nombre}.html", include_plotlyjs="cdn")
    except Exception as e:
        print("  (no se pudo exportar HTML de", nombre, ":", e, ")")
    if clave and _PNG_OK["estado"] is not False:
        try:
            fig.write_image(f"{DIRS['graficos']}/{nombre}.png", width=1100, height=650, scale=1.5)
            _PNG_OK["estado"] = True
        except Exception as e:
            ok = False
            if _PNG_OK["estado"] is None:           # primer fallo: intentar instalar Chrome para kaleido (plotly>=6)
                try:
                    pio.get_chrome()
                    fig.write_image(f"{DIRS['graficos']}/{nombre}.png", width=1100, height=650, scale=1.5)
                    ok = True
                except Exception:
                    ok = False
            _PNG_OK["estado"] = ok
            if not ok:
                print("  (PNG no disponible en este entorno; se exportan los gráficos en HTML interactivo)")
    return fig

