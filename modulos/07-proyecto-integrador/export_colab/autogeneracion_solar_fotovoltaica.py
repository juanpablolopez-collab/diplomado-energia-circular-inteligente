def tabla_calidad(d):
    filas = []
    def chk(regla, ok_mask):
        filas.append([regla, int((~ok_mask).sum()), f"{100 * ok_mask.mean():.1f}%"])
    chk("Sin valores nulos (por fila)", ~d.isna().any(axis=1))
    chk("id_hogar único", ~d.duplicated("id_hogar", keep=False))
    chk("Sin filas duplicadas", ~d.duplicated(keep=False))
    chk("Suma h00-h23 = consumo diario", np.isclose(d[HORAS].sum(axis=1), d["consumo_kwh_dia_promedio"], atol=1e-3))
    chk("Factura = consumo x tarifa", (d["consumo_kwh_mes"] * d["tarifa_kwh_cop"] - d["costo_factura_mes_cop"]).abs() <= 1)
    chk("Ahorro mensual <= factura", d["ahorro_mensual_cop"] <= d["costo_factura_mes_cop"])
    chk("Área requerida <= área cubierta", d["area_requerida_m2"] <= d["area_cubierta_m2"])
    chk("Consumo anual = 12 x mensual", (d["consumo_anual_kwh"] - 12 * d["consumo_kwh_mes"]).abs() < 0.2)
    chk("Menores + mayores < personas", (d["num_menores"] + d["num_adultos_mayores"]) < d["num_personas"])
    chk("Estrato 3 sin subsidio", ~((d["estrato"] == 3) & (d["recibe_subsidio"] == "Sí")))
    chk("Sin internet ni smartphone => IA 'Ninguno'",
        ~((d["tiene_internet"] == "No") & (d["tiene_smartphone"] == "No") & (d["dispositivo_ia_interes"] != "Ninguno")))
    chk("VPN>0 coherente con TIR>10%", (d["vpn_10_anios_cop"] > 0) == (d["tir_porcentaje"] > 10))
    return pd.DataFrame(filas, columns=["regla_de_coherencia", "filas_que_incumplen", "cumplimiento"])

