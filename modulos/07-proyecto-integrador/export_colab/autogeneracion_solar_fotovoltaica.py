# 2. Extracción de Embeddings usando un Encoder del Estado del Arte
print("\nCargando modelo de embeddings de lenguaje...")
embedding_model = SentenceTransformer('all-MiniLM-L6-v2', device=DEVICE)

print("Extrayendo embeddings para los 1000 hogares...")
embeddings = embedding_model.encode(df['narrativa_hogar'].tolist(), show_progress_bar=True, convert_to_numpy=True)

# 3. Preparación de Datasets y partición
y = df['dispuesto_instalar_paneles'].map({'No': 0, 'Tal vez': 1, 'Sí': 2}).astype(int).values

X_tr_emb, X_te_emb, y_tr_emb, y_te_emb = train_test_split(
    embeddings, y, test_size=0.20, stratify=y, random_state=SEED
)

class EmbeddingDataset(Dataset):
    def __init__(self, embs, targets):
        self.embs = torch.tensor(embs, dtype=torch.float32)
        self.targets = torch.tensor(targets, dtype=torch.long)

    def __len__(self):
        return len(self.embs)

    def __getitem__(self, idx):
        return self.embs[idx], self.targets[idx]

train_emb_dataset = EmbeddingDataset(X_tr_emb, y_tr_emb)
test_emb_dataset = EmbeddingDataset(X_te_emb, y_te_emb)

train_emb_loader = DataLoader(train_emb_dataset, batch_size=32, shuffle=True)
test_emb_loader = DataLoader(test_emb_dataset, batch_size=64, shuffle=False)

# 4. Definición del Clasificador sobre la representación del LLM
class LLMClassifier(nn.Module):
    def __init__(self, embedding_dim=384, num_classes=3):
        super(LLMClassifier, self).__init__()
        self.mlp = nn.Sequential(
            nn.Linear(embedding_dim, 128),
            nn.LayerNorm(128),
            nn.Mish(),
            nn.Dropout(0.3),
            nn.Linear(128, 64),
            nn.Mish(),
            nn.Dropout(0.2),
            nn.Linear(64, num_classes)
        )

    def forward(self, x):
        return self.mlp(x)

llm_clf = LLMClassifier(embedding_dim=embeddings.shape[1], num_classes=3).to(DEVICE)
criterion = nn.CrossEntropyLoss()
optimizer = optim.AdamW(llm_clf.parameters(), lr=1e-3, weight_decay=1e-3)

# 5. Entrenamiento del Modelo
print("\nIniciando entrenamiento del clasificador de embeddings LLM...")
epochs = 15
for epoch in range(1, epochs + 1):
    llm_clf.train()
    total_loss = 0.0
    for batch_embs, batch_ys in train_emb_loader:
        batch_embs, batch_ys = batch_embs.to(DEVICE), batch_ys.to(DEVICE)
        optimizer.zero_grad()
        outputs = llm_clf(batch_embs)
        loss = criterion(outputs, batch_ys)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * batch_embs.size(0)

    total_loss /= len(train_emb_loader.dataset)

    # Validación rápida
    llm_clf.eval()
    preds, reals = [], []
    with torch.no_grad():
        for batch_embs, batch_ys in test_emb_loader:
            batch_embs = batch_embs.to(DEVICE)
            outputs = llm_clf(batch_embs)
            preds.extend(outputs.argmax(dim=1).cpu().numpy())
            reals.extend(batch_ys.numpy())

    acc = accuracy_score(reals, preds)
    f1 = f1_score(reals, preds, average='macro')
    print(f"Época {epoch:02d}/{epochs:02d} | Train Loss: {total_loss:.4f} | Val Accuracy: {acc:.2%} | Val F1-Macro: {f1:.4f}")

# Evaluación final
print("\nReporte de Clasificación con Embeddings de LLM:")
print(classification_report(reals, preds, target_names=CLASES))

