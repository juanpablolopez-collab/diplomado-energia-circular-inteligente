# ---- 2.2 Bivariado
def fig_bivariado(x, y, color):
    col = None if color == "(ninguno)" else color
    num_x, num_y = x in NUM_EDA, y in NUM_EDA
    if num_x and num_y:
        try:
            fig = px.scatter(df, x=x, y=y, color=col if col is None else df[col].astype(str), trendline="ols", opacity=0.65,
                             title=f"{y} vs {x}")
        except Exception:
            fig = px.scatter(df, x=x, y=y, color=col if col is None else df[col].astype(str), opacity=0.65, title=f"{y} vs {x}")
        r, p = stats.pearsonr(df[x], df[y]); rho, _ = stats.spearmanr(df[x], df[y])
        fig.update_layout(title=f"{y} vs {x}  |  Pearson r={r:.2f}  Spearman ρ={rho:.2f}")
    elif (not num_x) and num_y:
        fig = px.box(df, x=x, y=y, color=x, points="outliers", title=f"{y} según {x}")
        grupos = [g[y].values for _, g in df.groupby(x)]
        if len(grupos) > 1:
            h, p = stats.kruskal(*grupos)
            fig.update_layout(title=f"{y} según {x}  |  Kruskal-Wallis H={h:.1f}, p={p:.2g}")
    elif num_x and (not num_y):
        fig = px.box(df, x=y, y=x, color=y, points="outliers", title=f"{x} según {y}")
    else:
        ct = pd.crosstab(df[x], df[y], normalize="index") * 100
        fig = px.imshow(ct.round(1), text_auto=True, aspect="auto", color_continuous_scale="Blues", title=f"% fila: {y} dentro de cada {x}")
        chi2, p, _, _ = stats.chi2_contingency(pd.crosstab(df[x], df[y]))
        fig.update_layout(title=f"{y} dentro de cada {x}  |  χ²={chi2:.1f}, p={p:.2g}")
    fig.update_layout(height=520)
    return fig

