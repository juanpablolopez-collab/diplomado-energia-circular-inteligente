# 1. Preparación de los datos textuales (Serialización de hogares a lenguaje natural)
def serializar_hogar(row):
    texto = f"Hogar de estrato {row['estrato']} ubicado en la zona {row['zona']}. "
    texto += f"Tiene {row['num_personas']} personas con un ingreso mensual de {row['ingreso_mensual_cop']:.0f} COP. "
    texto += f"El consumo eléctrico mensual es de {row['consumo_kwh_mes']:.1f} kWh, con una tarifa de {row['tarifa_kwh_cop']:.0f} COP por kWh. "
    texto += f"La vivienda tiene un área de {row['area_vivienda_m2']:.1f} m2 con {row['area_cubierta_m2']:.1f} m2 de cubierta disponible. "
    texto += f"Nivel educativo del jefe de hogar: {row['nivel_educativo']}. Ocupación principal: {row['ocupacion_principal']}. "
    texto += f"Tiene internet: {row['tiene_internet']}. Tiene smartphone: {row['tiene_smartphone']}. "
    texto += f"El retorno estimado de la inversión solar es a {row['retorno_simple_anios']:.1f} años con un ahorro del {row['porcentaje_ahorro']:.1f}%. "
    return texto

# Crear prompts narrativos
df['narrativa_hogar'] = df.apply(serializar_hogar, axis=1)

