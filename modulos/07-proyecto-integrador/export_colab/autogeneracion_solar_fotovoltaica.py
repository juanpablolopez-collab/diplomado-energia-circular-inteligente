def generar_series_sinteticas(df_, semilla=SEED):
    """Serie diaria sintética de 2 años (consumo y generación FV por hogar, kWh/día), calibrada con el dataset:
    nivel base = consumo y kWp medios de la muestra; estacionalidad bimodal de lluvias de Popayán (picos de lluvia en
    abril-mayo y octubre-noviembre), pico navideño de diciembre, efecto fin de semana, tendencia suave, ruido AR(1),
    nubosidad diaria y anomalías inyectadas (con etiqueta) para validar la detección."""
    rg = np.random.default_rng(semilla)
    fechas = pd.date_range(FECHA_INI, FECHA_FIN, freq="D"); n = len(fechas); doy = fechas.dayofyear.values
    cons0 = float(df_["consumo_kwh_dia_promedio"].mean()); kwp0 = float(df_["generacion_potencial_kwp"].mean())
    hsp0 = float(df_["horas_sol_pico"].mean()); amp_est = float(np.clip(df_["variacion_estacional_pct"].abs().mean() / 100, 0.02, 0.12))
    lluvia = np.cos(4 * np.pi * (doy - 120) / 365.0)                       # +1 en ~30-abr y ~30-oct (temporadas lluviosas)
    navidad = np.exp(-0.5 * ((((doy - 355) + 182) % 365 - 182) / 10.0) ** 2)
    findes = np.where(fechas.dayofweek >= 5, 1.06, 1.0)
    tend = 1 + 0.03 * np.arange(n) / 365.0
    ar = np.zeros(n)
    for t in range(1, n): ar[t] = 0.55 * ar[t - 1] + rg.normal(0, 0.028)
    consumo = cons0 * (1 + amp_est * lluvia + 0.07 * navidad) * findes * tend * np.exp(ar)
    etiqueta = np.zeros(n, dtype=int)
    idx_an = rg.choice(np.arange(20, n - 20), 12, replace=False)
    for j, t in enumerate(idx_an):
        consumo[t] *= rg.uniform(1.45, 1.9) if j % 4 != 3 else rg.uniform(0.45, 0.6); etiqueta[t] = 1
    nubes = np.clip(1 - 0.10 * (lluvia > 0.2) * lluvia + rg.normal(0, 0.12, n), 0.30, 1.20)
    gen = kwp0 * hsp0 * 0.78 * (1 - 0.10 * np.clip(lluvia, 0, 1)) * np.clip(nubes, 0.3, 1.2) * (1 - 0.005 * np.arange(n) / 365.0)
    return pd.DataFrame({"consumo_kwh_dia": consumo, "generacion_kwh_dia": gen, "anomalia_real": etiqueta}, index=fechas)

