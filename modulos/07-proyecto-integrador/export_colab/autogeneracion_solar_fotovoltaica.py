def _resolver_pulp(beneficio, costo, caps, presupuesto, min_share):
    """PuLP (<4). Las variables se crean con argumentos POSICIONALES (nombre, cota inf., cota sup., categoría),
    que es lo que evita el TypeError reportado con keywords en algunas versiones."""
    prob = pulp.LpProblem("Subsidios_FV_Popayan", pulp.LpMaximize)
    x = {s: pulp.LpVariable(f"E{s}", 0, caps[s], pulp.LpInteger) for s in (1, 2, 3)}
    prob += pulp.lpSum(beneficio[s] * x[s] for s in x), "Beneficio_total"
    prob += pulp.lpSum(costo[s] * x[s] for s in x) <= presupuesto, "Presupuesto"
    if min_share > 0:
        prob += costo[1] * x[1] - min_share * pulp.lpSum(costo[s] * x[s] for s in x) >= 0, "Equidad_E1"
    prob.solve(pulp.PULP_CBC_CMD(msg=0))
    if pulp.LpStatus[prob.status] != "Optimal":
        return None, pulp.LpStatus[prob.status]
    return {s: int(round(x[s].value() or 0)) for s in x}, "Optimal"

def _resolver_scipy(beneficio, costo, caps, presupuesto, min_share):
    """Respaldo con scipy.optimize.milp (HiGHS): mismo modelo, se usa si PuLP no está disponible o es >= 4."""
    from scipy.optimize import milp, LinearConstraint, Bounds
    c = -np.array([beneficio[s] for s in (1, 2, 3)])
    co = np.array([costo[s] for s in (1, 2, 3)])
    A = [co]; ub = [presupuesto]
    if min_share > 0:
        fila = min_share * co.copy(); fila[0] = -(1 - min_share) * co[0]
        A.append(fila); ub.append(0.0)
    r = milp(c, constraints=LinearConstraint(np.array(A), -np.inf, np.array(ub)), integrality=np.ones(3),
             bounds=Bounds(np.zeros(3), np.array([caps[s] for s in (1, 2, 3)], float)))
    if not r.success:
        return None, r.message
    return {s: int(round(r.x[i])) for i, s in enumerate((1, 2, 3))}, "Optimal"

def _resolver(beneficio, costo, caps, presupuesto, min_share):
    try:
        if int(str(pulp.__version__).split(".")[0]) >= 4:
            raise RuntimeError("PuLP >= 4 usa otra API; se usa scipy.optimize.milp")
        sol = _resolver_pulp(beneficio, costo, caps, presupuesto, min_share); SOLVER_USADO["nombre"] = "PuLP + CBC"
        return sol
    except Exception:
        SOLVER_USADO["nombre"] = "scipy.optimize.milp (HiGHS)"
        return _resolver_scipy(beneficio, costo, caps, presupuesto, min_share)

def optimizar(presupuesto_mm=1000.0, sub1=0.80, sub2=0.50, sub3=0.20, min_share_e1=0.0, w_en=0.5, w_hog=0.3, w_ah=0.2):
    sub = {1: sub1, 2: sub2, 3: sub3}
    tw = max(w_en + w_hog + w_ah, 1e-9); w_en, w_hog, w_ah = w_en / tw, w_hog / tw, w_ah / tw
    costo = {s: PAR[s]["inversion"] * sub[s] for s in sub}
    en_max = max(PAR[s]["energia_vida_kwh"] for s in sub); ah_max = max(PAR[s]["ahorro_10a_cop"] for s in sub)
    beneficio = {s: w_en * PAR[s]["energia_vida_kwh"] / en_max + w_hog * 1.0 + w_ah * PAR[s]["ahorro_10a_cop"] / ah_max for s in sub}
    caps = {s: PAR[s]["elegibles"] for s in sub}
    sol, estado = _resolver(beneficio, costo, caps, presupuesto_mm * 1e6, min_share_e1)
    if sol is None:
        return None, str(estado)
    filas = []
    for s in (1, 2, 3):
        n = int(sol[s])
        filas.append({"estrato": f"E{s}", "subsidio_%": int(sub[s] * 100), "sistemas": n, "subsidio_por_sistema_cop": round(costo[s]), "gasto_municipal_cop": round(costo[s] * n),
                      "inversion_total_cop": round(PAR[s]["inversion"] * n), "hogares_atendidos": n, "energia_vida_util_MWh": round(PAR[s]["energia_vida_kwh"] * n / 1000, 1),
                      "CO2_evitado_t": round(PAR[s]["co2_vida_t"] * n, 1), "ahorro_familias_10a_cop": round(PAR[s]["ahorro_10a_cop"] * n)})
