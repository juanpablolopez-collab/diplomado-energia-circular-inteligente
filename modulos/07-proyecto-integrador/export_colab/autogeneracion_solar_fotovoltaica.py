def pronostico_prophet(m, h):
    fut = m.make_future_dataframe(periods=h, freq="D"); fc = m.predict(fut).iloc[-h:]
    try:
        samp = np.asarray(m.predictive_samples(fut)["yhat"])[-h:, :]
    except Exception:
        samp = None
    return pd.DatetimeIndex(fc["ds"]), fc["yhat"].values, samp

