import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from sklearn.preprocessing import LabelEncoder

# --- 1. Definición de la Red Neuronal Multimodular HogarAdopcionNet ---
class HogarAdopcionNet(nn.Module):
    def __init__(self, num_numeric_features, cat_cardinalities, embed_dims, temporal_dim=24):
        super(HogarAdopcionNet, self).__init__()

        # A. Rama Numérica (Tabular Continua)
        self.numeric_branch = nn.Sequential(
            nn.Linear(num_numeric_features, 64),
            nn.BatchNorm1d(64),
            nn.Mish(),
            nn.Dropout(0.25),
            nn.Linear(64, 32),
            nn.Mish()
        )

        # B. Rama Categórica (Embeddings dedicados)
        self.embeddings = nn.ModuleList([
            nn.Embedding(num_classes, dim) for num_classes, dim in zip(cat_cardinalities, embed_dims)
        ])
        total_embed_dim = sum(embed_dims)
        self.categorical_branch = nn.Sequential(
            nn.Linear(total_embed_dim, 32),
            nn.Mish(),
            nn.Dropout(0.20)
        ) if total_embed_dim > 0 else nn.Identity()

        # C. Rama Temporal (Perfil horario de 24 horas)
        self.temporal_branch = nn.Sequential(
            nn.Linear(temporal_dim, 32),
            nn.BatchNorm1d(32),
            nn.Mish(),
            nn.Dropout(0.20),
            nn.Linear(32, 16),
            nn.Mish()
        )

        # Fusión Tardía y Clasificador Final
        fusion_dim = 32 + (32 if total_embed_dim > 0 else 0) + 16
        self.classifier = nn.Sequential(
            nn.Linear(fusion_dim, 32),
            nn.Mish(),
            nn.Dropout(0.20),
            nn.Linear(32, 3), # 3 clases de salida: No, Tal vez, Sí
            nn.LogSoftmax(dim=1)
        )

    def forward(self, x_num, x_cat, x_temp):
        # Procesamiento de cada rama
        out_num = self.numeric_branch(x_num)

        if len(self.embeddings) > 0:
            embeds = [emb(x_cat[:, i]) for i, emb in enumerate(self.embeddings)]
            out_cat = torch.cat(embeds, dim=1)
            out_cat = self.categorical_branch(out_cat)
        else:
            out_cat = None

        out_temp = self.temporal_branch(x_temp)

        # Fusión tardía de representaciones latentes
        if out_cat is not None:
            fused = torch.cat([out_num, out_cat, out_temp], dim=1)
        else:
            fused = torch.cat([out_num, out_temp], dim=1)

        return self.classifier(fused)

# --- 2. Dataset Custom de PyTorch para Carga Eficiente ---
class MultimodalDataset(Dataset):
    def __init__(self, df_features, num_cols, cat_cols, temp_cols, targets=None):
        self.x_num = torch.tensor(df_features[num_cols].values, dtype=torch.float32)
        self.x_cat = torch.tensor(df_features[cat_cols].values, dtype=torch.long)
        self.x_temp = torch.tensor(df_features[temp_cols].values, dtype=torch.float32)
        self.targets = torch.tensor(targets, dtype=torch.long) if targets is not None else None

    def __len__(self):
        return len(self.x_num)

    def __getitem__(self, idx):
        if self.targets is not None:
            return self.x_num[idx], self.x_cat[idx], self.x_temp[idx], self.targets[idx]
        return self.x_num[idx], self.x_cat[idx], self.x_temp[idx]

print("Estructura del clasificador multimodal HogarAdopcionNet y su Dataset inicializados correctamente.")

